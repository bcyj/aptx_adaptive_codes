/* Implements verify_tree. */
static int verify_tree(int root, const AACode *codes, unsigned count) {
    unsigned i, bit;
    int checked = 0;
    for (i = 0; i < count; ++i) {
        int node = root;
        if (!codes[i].len) continue;
        for (bit = codes[i].len; bit; --bit) {
            if (node < 0 || (unsigned)node >= AA_DECODE_NODE_COUNT || AA_DECODE_NODES[node].symbol >= 0)
                return -1;
            node = AA_DECODE_NODES[node].child[(codes[i].code >> (bit - 1)) & 1];
        }
        if (node < 0 || (unsigned)node >= AA_DECODE_NODE_COUNT || AA_DECODE_NODES[node].symbol != (int)i)
            return -1;
        ++checked;
    }
    return checked;
}

/* Implements aa_decode_verify_tables. */
int aa_decode_verify_tables(void) {
    unsigned i;
    int count = 0, n;
    const AACode *codes[4] = {T1, T2, T3, T4};
    const unsigned sizes[4] = {16, 16, 64, 256};
    n = verify_tree(AA_DECODE_ABS_ROOT[0], ABS_A, 138); if (n < 0) return -1; count += n;
    n = verify_tree(AA_DECODE_ABS_ROOT[1], ABS_B, 138); if (n < 0) return -1; count += n;
    for (i = 0; i < 9; ++i) {
        n = verify_tree(AA_DECODE_DIFF_ROOT[i], DIFF[i], 16); if (n < 0) return -1; count += n;
    }
    for (i = 0; i < 4; ++i) {
        n = verify_tree(AA_DECODE_CODE_ROOT[i + 1], codes[i], sizes[i]); if (n < 0) return -1; count += n;
    }
    return count;
}
