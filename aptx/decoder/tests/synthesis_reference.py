"""Derive synthesis FIRs from the linear analysis banks (no external packages).

The 8x16 cosine transform has T T^t = 8 I. The complete critically sampled
analysis banks are paraunitary up to gains 1/8 (tree) and 1/64 (cosine).
Time-reversed transpose FIRs with gains 8/64 therefore synthesize PCM.
This derives a functional synthesis bank; it does not reproduce a vendor
decoder's fixed-point implementation/rounding. Emit both double coefficients
and signed Q29 coefficients with a checked int64 accumulator bound. Only the
selected backend's table is compiled. Coefficients are checked in.
"""
from pathlib import Path
import re
import math

root=Path(__file__).resolve().parents[3]
source=(root/'aptx/common/src/tables/codec_tables.c').read_text(encoding='utf-8')
def table(name):
    body=re.search(r'const int32_t '+name+r'\[.*?\] = \{(.*?)\};',source,re.S)[1]
    return list(map(int,re.findall(r'-?\d+',body)))

def transform(u):
    front=[([8,15],[7,0],4,297678104,0,3022376512),([9,14],[6,1],3,881594710,7,2906228278),
           ([10,13],[5,2],5,1431632125,1,2678395321),([11,12],[4,3],2,1926652721,6,2347633133)]
    dct=table('DCT')
    o=[0.0]*8
    for add,sub,di,dc,si,sc in front:
        pos=u[add[0]]+u[add[1]]; neg=u[sub[0]]-u[sub[1]]
        o[di]=(pos-neg)*dc/2**31; o[si]=(pos+neg)*sc/2**31
    mul=lambda v,i:v*dct[i]/2**31
    s04=o[0]+o[4];s26=o[2]+o[6];s15=o[1]+o[5];s37=o[3]+o[7]
    a=mul(o[0]-o[4],0);b=mul(o[1]-o[5],1);c=mul(o[3]-o[7],2);d=mul(o[2]-o[6],3)
    ad=a+d;bc=b+c;s0=s04+s26;s1=s15+s37
    g=mul(s04-s26,4);h=mul(s15-s37,5);e=mul(a-d,4);f=mul(b-c,5)
    y=[0.0]*8
    y[0]=s0+s1;y[1]=ad+bc;y[2]=g+h;y[4]=mul(s0-s1,6)
    y[3]=2*(e+f)-y[1];y[5]=2*mul(ad-bc,6)-y[3]
    y[6]=2*mul(g-h,6)-y[2];y[7]=2*(2*mul(e-f,6)-(e+f))-y[5]
    y[0]/=2
    for i in range(1,8): y[i]-=y[i-1]
    return y

def cosine(taps):
    cols=[transform([float(i==j) for i in range(16)]) for j in range(16)]
    proto=table('PROTO_'+str(taps))
    return [[-cols[lag%16][k]*proto[lag]/2**28 for lag in range(taps)] for k in range(8)]

def tree(taps):
    co,ci=table('OUTER_'+str(taps)),table('INNER_'+str(taps))
    h=[[0.0]*(6*taps-2) for _ in range(4)]
    for ki in range(taps):
        for ko in range(taps):
            for pair in range(2):
                for eo in range(2):
                    lag=3+4*ki-2*pair+2*ko-eo
                    v=ci[ki if pair==0 else taps-1-ki]*co[ko if eo==0 else taps-1-ko]/2**43
                    ps=-1 if pair==0 else 1; es=-1 if eo==0 else 1
                    h[0][lag]+=v;h[1][lag]+=v*ps;h[3][lag]+=v*es;h[2][lag]+=v*ps*es
    return h

if __name__=='__main__':
    output=['/* Generated by aptx/decoder/tests/synthesis_reference.py. */',
            '#include "aa_synthesis.h"']
    banks=[('AA_SYNTH_0',tree(16)),('AA_SYNTH_1',tree(12)),
           ('AA_SYNTH_3',cosine(256)),('AA_SYNTH_4',cosine(128))]
    output.append('#if APTX_AA_DECODER_FIXED_POINT')
    for name,h in banks:
        q=[[math.floor(v*2**29+.5) for v in row] for row in h]
        assert all(-2**31<=v<2**31 for row in q for v in row)
        phase_l1=max(sum(abs(row[lag]) for row in q for lag in range(p,len(row),len(q))) for p in range(len(q)))
        # Includes partial sums, overlap across input blocks, and rounding bias.
        bound=phase_l1*2**23+2**28
        assert bound<2**63
        output += [f'/* {name}: max phase L1={phase_l1}; |acc|+round <= {bound}. */',
                   f'_Static_assert(INT64_C({phase_l1}) <= (INT64_MAX - INT64_C(268435456)) / INT64_C(8388608),',
                   '               "synthesis accumulator bound");',
                   f'const AASynthCoeff {name}[{len(q)}][{len(q[0])}] = {{']
        for row in q:
            output.append('    {')
            for at in range(0,len(row),8):output.append('        '+', '.join(map(str,row[at:at+8]))+',')
            output.append('    },')
        output.append('};')
    output.append('#else')
    for name,h in banks:
        output.append(f'const AASynthCoeff {name}[{len(h)}][{len(h[0])}] = {{')
        for row in h:
            output.append('    {')
            for at in range(0,len(row),4):
                output.append('        '+', '.join(format(v,'.17g') for v in row[at:at+4])+',')
            output.append('    },')
        output.append('};')
    output.append('#endif')
    (root/'aptx/decoder/src/dsp/synthesis_tables.c').write_text('\n'.join(output)+'\n',encoding='utf-8')
    print('Generated synthesis FIRs for configs 0/1/3/4')
