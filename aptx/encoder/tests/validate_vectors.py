"""Byte-for-byte checks against the original repository's reference captures.

Usage: python tests/validate_vectors.py build/aptx_aa.dll
The PCM and golden packets are checked-in fixtures, not generated by the C port.
"""
import argparse
import ctypes as C
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
ap = argparse.ArgumentParser()
ap.add_argument('library', type=Path)
ap.add_argument('--vectors', type=Path, default=ROOT/'tests/vectors')
args = ap.parse_args()
lib = C.CDLL(str(args.library.resolve()))
import runpy
constructor=runpy.run_path(str(ROOT/'tests/support/allocator.py'))['constructor']
create=constructor(lib,'aptx_aa_create_variant',C.c_uint,C.c_uint32,C.c_uint32,C.c_size_t)

class Progress(C.Structure):
    _fields_ = [('consumed',C.c_size_t),('written',C.c_size_t)]
lib.aptx_aa_create_variant.argtypes=[C.c_uint,C.c_uint32,C.c_uint32,C.c_size_t]
lib.aptx_aa_create_variant.restype=C.c_void_p
lib.aptx_aa_destroy.argtypes=[C.c_void_p]
lib.aptx_aa_encode.argtypes=[C.c_void_p,C.POINTER(C.c_int32),C.c_size_t,
                            C.POINTER(C.c_int32),C.c_size_t,C.c_void_p,C.c_size_t,
                            C.POINTER(Progress)]
lib.aptx_aa_flush.argtypes=[C.c_void_p,C.c_void_p,C.c_size_t,C.POINTER(C.c_size_t)]
lib.aptx_aa_set_bitrate.argtypes=[C.c_void_p,C.c_uint32]

def check(status):
    if status:
        raise RuntimeError('C encoder status '+str(status))

def run_vector(name,level,profile,rate,bitrate,ms,packet,chunk,ll):
    variant=1 if profile==1 else (3 if rate>48000 or (level=='R2' and not ll) else (4 if level=='R2' else 0))
    pcm=(args.vectors/'parity'/f'mix{rate}.s32le').read_bytes()
    enc=create(variant,rate,bitrate,packet)
    if not enc:
        raise RuntimeError('create failed')
    output=C.create_string_buffer(packet)
    queue=bytearray(); packets=bytearray(); forced=[]
    consumed=deficit=0; period=ms*rate*2//1000
    try:
        for at in range(0,len(pcm),chunk*8):
            queue.extend(pcm[at:at+chunk*8])
            samples=len(queue)//4
            data=(C.c_int32*samples).from_buffer_copy(queue)
            p=Progress()
            check(lib.aptx_aa_encode(enc,data,samples,None,0,output,packet,C.byref(p)))
            del queue[:p.consumed*4]
            consumed+=p.consumed
            if not p.written and consumed<period+deficit:
                continue
            was_forced=not p.written
            if was_forced:
                n=C.c_size_t()
                check(lib.aptx_aa_flush(enc,output,packet,C.byref(n)))
                if n.value!=packet:
                    raise RuntimeError('flush did not produce due packet')
            packets.extend(output.raw); forced.append(was_forced)
            deficit+=period-consumed; consumed=0
            if ll:
                deficit=0
            check(lib.aptx_aa_set_bitrate(enc,bitrate-bitrate//4 if deficit>96 else bitrate))
    finally:
        lib.aptx_aa_destroy(enc)
    want=(args.vectors/'parity'/(name+'.bin')).read_bytes()
    want_forced=[line.endswith(' 1') for line in (args.vectors/'parity'/(name+'.sizes')).read_text().splitlines()]
    if packets!=want:
        at=next((i for i,(a,b) in enumerate(zip(packets,want)) if a!=b),min(len(packets),len(want)))
        raise AssertionError(f'{name}: first difference packet {at//packet} byte {at%packet}; sizes {len(packets)}/{len(want)}')
    assert forced==want_forced, name+': flush flags differ'
    return len(forced),len(want)

results=[]
for line in (args.vectors/'parity/runs.txt').read_text().splitlines():
    if not line.strip() or line.lstrip().startswith('#'):
        continue
    fields=line.split(); name,level=fields[:2]; numbers=list(map(int,fields[2:]))
    try:
        packets,bytes_=run_vector(name,level,*numbers)
        print('PASS',name,packets,'packets',flush=True)
        results.append({'name':name,'passed':True,'packets':packets,'bytes':bytes_})
    except Exception as ex:
        print('FAIL',ex,flush=True)
        results.append({'name':name,'passed':False,'error':str(ex)})
report={'passed':sum(r['passed'] for r in results),'total':len(results),'runs':results}
(ROOT/'build').mkdir(exist_ok=True)
(ROOT/'build/vector-results.json').write_text(json.dumps(report,indent=2))
print('Reference vector runs:',report['passed'],'/',report['total'])
sys.exit(0 if report['passed']==report['total'] else 1)
